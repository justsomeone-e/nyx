def _nyx_type(type_node: object) -> str:
    if type_node is None:
        return VOID
    name = getattr(type_node, "name", str(type_node))
    if name in ("int", "bool"):
        return I32
    if name == "float":
        return F64
    if name == "string":
        return STRING
    if name == "void":
        return VOID
    return str(name)


def _binary_opcode(op: str, operand_type: str) -> str:
    if operand_type == F64:
        opcodes = {
            "+": "f64.add", "-": "f64.sub", "*": "f64.mul", "/": "f64.div",
            "==": "f64.eq", "!=": "f64.ne", "<": "f64.lt", ">": "f64.gt",
            "<=": "f64.le", ">=": "f64.ge",
        }
    else:
        opcodes = {
            "+": "i32.add", "-": "i32.sub", "*": "i32.mul", "/": "i32.div_s", "%": "i32.rem_s",
            "&": "i32.and", "|": "i32.or", "^": "i32.xor", "<<": "i32.shl", ">>": "i32.shr_s",
            "and": "i32.and", "&&": "i32.and", "or": "i32.or", "||": "i32.or",
            "==": "i32.eq", "!=": "i32.ne", "<": "i32.lt_s", ">": "i32.gt_s",
            "<=": "i32.le_s", ">=": "i32.ge_s",
        }
    if op not in opcodes:
        raise BundleCompileError(f"Operator '{op}' is unsupported for WASM type '{operand_type}'")
    return opcodes[op]


def _definitely_returns(statements: Iterable[IRStatement]) -> bool:
    """Return whether every reachable path through a statement list returns.

    A value-producing WASM function cannot legally fall through to its implicit
    function end.  Merely finding a nested ``return`` is insufficient: an
    ``if`` without an ``else`` can still take the fall-through path.  This
    deliberately conservative analysis accepts straight-line returns and
    exhaustive if/elif/else chains; loops are not considered terminating
    because ``break`` and zero-iteration paths need control-flow analysis.
    """
    for statement in statements:
        if isinstance(statement, IRReturn):
            return True
        if isinstance(statement, IRIf):
            if _if_definitely_returns(statement):
                return True
    return False


def _if_definitely_returns(statement: IRIf) -> bool:
    """Return whether every branch of an ``if`` chain returns a value."""
    if statement.else_branch is None:
        return False
    if not _definitely_returns(statement.then_branch):
        return False
    if any(not _definitely_returns(branch) for _, branch in statement.elif_branches):
        return False
    return _definitely_returns(statement.else_branch)


def _align8(value: int) -> int:
    return (value + 7) & -8


def _u32(value: int) -> bytes:
    if value < 0:
        raise ValueError("u32 LEB128 cannot encode a negative value")
    output = bytearray()
    while True:
        byte = value & 0x7F
        value >>= 7
        if value:
            byte |= 0x80
        output.append(byte)
        if not value:
            return bytes(output)


def _signed_leb(value: int, bits: int) -> bytes:
    output = bytearray()
    more = True
    while more:
        byte = value & 0x7F
        value >>= 7
        sign_set = byte & 0x40
        more = not ((value == 0 and not sign_set) or (value == -1 and sign_set))
        if more:
            byte |= 0x80
        output.append(byte)
    return bytes(output)


def _s32(value: int) -> bytes:
    return _signed_leb(value, 32)


def _s64(value: int) -> bytes:
    return _signed_leb(value, 64)


def _string(value: str) -> bytes:
    encoded = value.encode("utf-8")
    return _u32(len(encoded)) + encoded


def _append_section(wasm: bytearray, section_id: int, payload: bytes) -> None:
    wasm.append(section_id)
    wasm.extend(_u32(len(payload)))
    wasm.extend(payload)


def _wat_bytes(data: bytes) -> str:
    result = []
    for byte in data:
        if 0x20 <= byte <= 0x7E and byte not in (0x22, 0x5C):
            result.append(chr(byte))
        else:
            result.append(f"\\{byte:02x}")
    return "".join(result)
